    t2 = np.array(an.time)*1e6; ue = np.array(an['e']); ua2 = np.array(an['a'])
    axes[1].plot(t2, ue, color='gray', lw=1, label='прикладена напруга')
    axes[1].plot(t2, ua2, color='#2563eb', lw=2, label='$u_{АК}$')
